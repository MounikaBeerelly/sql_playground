-- CREATE SOURCE TABLE
CREATE SOURCE_TABLE_SCD3 (
    EMPLOYEE_ID VARCHAR2(50),
    EMPLOYEE_NAME VARCHAR2(100),
    GENDER VARCHAR2(10),
    STATUS VARCHAR2(10),
    HIRE_DATE DATE
);

-- LOAD THE CHANGED DATA TO SOURCE TABLE
INSERT INTO SOURCE_TABLE_SCD3 VALUES ('E001', 'Sathish Kumar Y', 'MALE', DATE '2023-06-01', 'ACTIVE');
INSERT INTO SOURCE_TABLE_SCD3 VALUES ('E002', 'Anita Sharma', 'FEMALE', DATE '2022-03-15', 'INACTIVE');
