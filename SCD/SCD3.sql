COMMIT;

-- STEP 1 : UPDATE CHANGED RECORDS
UPDATE TARGET_TABLE_SCD3 T
SET
    -- SHIFT CURRENT VALUE TO PREVIOUS VALUE
    PREV_EMPLOYEE_NAME = T.EMPLOYEE_NAME,
    PREV_STATUS = T.STATUS,
    -- SET THE NEW CURRENT VALUES
    EMPLOYEE_NAME = (
            SELECT S.EMPLOYEE_NAME
            FROM SOURCE_TABLE_SCD3
            WHERE S.EMPLOYEE_ID = T.EMPLOYEE_ID
            ),
    STATUS = (
            SELECT S.STATUS
            FROM SOURCE_TABLE_SCD3 S
            WHERE S.EMPLOYEE_ID = T.EMPLOYEE_ID
        )
WHERE EXISTS (
                SELECT 1
                FROM SOURCE_TABLE_SCD3 S
                WHERE S.EMPLOYEE_ID = T.EMPLOYEE_ID
                AND (
                    NVL(T.EMPLOYEE_NAME, 'X') <> NVL(S.EMPLOYEE_NAME, 'X') OR
                    NVL(T.STATUS, 'X') <> NVL(S.STATUS, 'X')
                    )
);

-- STEP 2: INSERT NEW RECORDS INTO TARGET TABLE
INSERT INTO TARGET_TABLE_SCD3 (
    EMPLOYEE_KEY,
    EMPLOYEE_ID,
    EMPLOYEE_NAME,
    PREV_EMPLOYEE_NAME,
    GENDER,
    STATUS,
    PREV_STATUS,
    HIRE_DATE
    )
SELECT
    SEQ_EMP.NEXTVAL,
    S.EMPLOYEE_ID,
    S.EMPLOYEE_NAME,
    NULL,
    S.GENDER,
    S.STATUS,
    NULL,
    S.HIRE_DATE
FROM SOURCE_TABLE_SCD3 S
WHERE NOT EXISTS (
    SELECT 1
    FROM TARGET_TABLE_SCD3 T
    WHERE T.EMPLOYEE_ID = S.EMPLOYEE_ID
);

-- MERGE STATEMENT
MERGE INTO TARGET_TABLE_SCD3 T
USING SOURCE_TABLE_SCD3 S
ON (T.EMPLOYEE_ID = S.EMPLOYEE_ID)
WHEN MATCHED THEN
UPDATE SET
    -- SHIFTING CURRENT EMPLOYEE NAME TO PREVIOUS EMPLOYEE NAME IF CHANGED
    T.PREV_EMPLOYEE_NAME =
            CASE
                WHEN NVL(T.EMPLOYEE_NAME, 'X') <> NVL(S.EMPLOYEE_NAME, 'X')
                THEN T.EMPLOYEE_NAME
                ELSE T.PREV_EMPLOYEE_NAME
            END,
    T.PREV_STATUS =
            CASE
                WHEN NVL(T.STATUS, 'X') <> NVL(S.STATUS, 'X')
                THEN T.STATUS
                ELSE T.PREV_STATUS
            END,
    T.EMPLOYEE_NAME = S.EMPLOYEE_NAME,
    T.STATUS = S.STATUS,
    T.GENDER = S.GENDER,
    T.HIRE_DATE = S.HIRE_DATE
WHEN NOT MATCHED THEN
INSERT (
    EMPLOYEE_KEY,
    EMPLOYEE_ID,
    EMPLOYEE_NAME,
    PREV_EMPLOYEE_NAME,
    GENDER,
    STATUS,
    PREV_STATUS,
    HIRE_DATE
)
VALUES (
    SEQ_EMP.NEXTVAL,
    S.EMPLOYEE_ID,
    S.EMPLOYEE_NAME,
    NULL,
    S.GENDER,
    S.STATUS,
    NULL,
    S.HIRE_DATE
);
