     D.EMPLOYEE_NAME,
     D.GENDER,
     D.HIRE_DATE,
     D.STATUS) = (
                    SELECT
                        S.EMPLOYEE_ID,
                        S.EMPLOYEE_NAME,
                        S.GENDER,
                        S.HIRE_DATE,
                        S.STATUS
                    FROM STG_EMPLOYEE01 S
