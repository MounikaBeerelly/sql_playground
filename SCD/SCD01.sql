-- MERGE update and insert queries
    -- Note : ThIS Merge UPDATES All The Records, Including Changes and Unchanged : Non Optimized Implementation
MERGE INTO DIM_EMPLOYEE01 D
USING STG_EMPLOYEE01 S
ON (D.EMPLOYEE_ID = S.EMPLOYEE_ID)
WHEN MATCHED THEN
UPDATE SET
    D.EMPLOYEE_NAME = S.EMPLOYEE_NAME,
    D.GENDER = S.GENDER,
    D.HIRE_DATE = S.HIRE_DATE,
    D.STATUS = S.STATUS
WHEN NOT MATCHED THEN
INSERT (
    EMPLOYEE_KEY,
    EMPLOYEE_ID,
    EMPLOYEE_NAME,
    GENDER,
    HIRE_DATE,
    STATUS
)
VALUES (
    EMP_SEQ.NEXTVAL,
    S.EMPLOYEE_ID,
    S.EMPLOYEE_NAME,
    S.GENDER,
    S.HIRE_DATE,
    S.STATUS
);

-- MERGE (OPTIMIZED QUERY) - ONLY UPDATED AND NEW RECORDS WILL MERGE
    -- Note : ThIS Merge UPDATES Only The Records, Excluding Unchanged Records : Optimized Implementation
MERGE INTO DIM_EMPLOYEE01 D
USING STG_EMPLOYEE01 S
ON (D.EMPLOYEE_ID = S.EMPLOYEE_ID)
WHEN MATCHED THEN
UPDATE SET
    D.EMPLOYEE_NAME = S.EMPLOYEE_NAME,
    D.GENDER = S.GENDER,
    D.HIRE_DATE = S.HIRE_DATE,
    D.STATUS = S.STATUS
WHERE
    NVL(D.EMPLOYEE_NAME, 'X') <> NVL(S.EMPLOYEE_NAME, 'X') OR
    NVL(D.GENDER, 'X') <> NVL(S.GENDER, 'X') OR
    NVL(D.HIRE_DATE, DATE '1990-01-01') <> NVL(S.HIRE_DATE, DATE '1990-01-01') OR
    NVL(D.STATUS, 'X') <> NVL(S.STATUS, 'X')
WHEN NOT MATCHED THEN
INSERT (
    EMPLOYEE_KEY,
    EMPLOYEE_ID,
    EMPLOYEE_NAME,
    GENDER,
    HIRE_DATE,
    STATUS
)
VALUES (
    EMP_SEQ.NEXTVAL,
    S.EMPLOYEE_ID,
