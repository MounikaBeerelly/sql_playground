-- CREATE SOURCE TABLE
CREATE TABLE SOURCE_TABLE_SCD1 (
    STUDENT_ID VARCHAR2(10),
    STUDENT_NAME VARCHAR2(30),
    AGE NUMBER(2),
    CLASS NUMBER (2),
    GRADE CHAR(1)
);

