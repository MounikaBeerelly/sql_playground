-- IMPLEMENTING SCD 1

-- STEP 1 : UPDATE CHANGED RECORDS
UPDATE TARGET_TABLE_SCD1 T
SET (T.STUDENT_ID,
     T.STUDENT_NAME,
     T.AGE,
     T.CLASS,
     T.GRADE ) = (
                    SELECT
                        S.STUDENT_ID,
                        S.STUDENT_NAME,
                        S.AGE,
                        S.CLASS,
                        S.GRADE
                    FROM SOURCE_TABLE_SCD1 S
                    WHERE S.STUDENT_ID = T.STUDENT_ID
                )
WHERE EXISTS (
    SELECT 1
    FROM SOURCE_TABLE_SCD1 S
    WHERE S.STUDENT_ID = T.STUDENT_ID
);

-- STEP 2: INSERT NEW RECORDS INTO TARGET TABLE
INSERT INTO TARGET_TABLE_SCD1 (
    STUDENT_KEY,
    STUDENT_ID,
    STUDENT_NAME,
    AGE,
    CLASS,
    GRADE
)
SELECT
    STUDENT_SEQ.NEXTVAL,
    S.STUDENT_ID,
    S.STUDENT_NAME,
    S.AGE,
    S.CLASS,
    S.GRADE
    FROM SOURCE_TABLE_SCD1 S
WHERE NOT EXISTS (
    SELECT 1
    FROM TARGET_TABLE_SCD1 T
    WHERE T.STUDENT_ID = S.STUDENT_ID
);

-- STEP 3 : MERGE UPDATE AND INSERT QUERIES
MERGE INTO TARGET_TABLE_SCD1 T
USING SOURCE_TABLE_SCD1 S
ON (T.STUDENT_ID = S.STUDENT_ID)
WHEN MATCHED THEN
UPDATE SET
    T.STUDENT_NAME = S.STUDENT_NAME,
    T.AGE = S.AGE,
    T.CLASS = S.CLASS,
    T.GRADE = S.GRADE
WHERE
    NVL(T.STUDENT_NAME, 'X') <> NVL(S.STUDENT_NAME, 'X') OR
    NVL(T.AGE, -1) <> NVL(S.AGE, -1) OR
    NVL(T.CLASS, -1) <> NVL(S.CLASS, -1) OR
    NVL(T.GRADE, 'X') <> NVL(S.GRADE, 'X')
WHEN NOT MATCHED THEN
INSERT (
    STUDENT_KEY,
    STUDENT_ID,
    STUDENT_NAME,
    AGE,
    CLASS,
    GRADE
)
VALUES (
    STUDENT_SEQ.NEXTVAL,
    S.STUDENT_ID,
    S.STUDENT_NAME,
    S.AGE,
    S.CLASS,
    S.GRADE
);